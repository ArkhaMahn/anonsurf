#!/usr/bin/env python3
"""Assemble an Arch pacman package (.pkg.tar.zst) from an installed file tree.

This mirrors what ``makepkg`` produces: metadata files at the archive root
(.PKGINFO, .BUILDINFO, .MTREE and optionally .INSTALL) followed by the payload.
It exists because this build environment is not Arch based, so ``makepkg`` is
unavailable here.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import time


def installed_size(root: str) -> int:
    total = 0
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in filenames:
            path = os.path.join(dirpath, name)
            if os.path.islink(path):
                continue
            total += os.path.getsize(path)
    return total


def write_pkginfo(path: str, meta: dict[str, list[str] | str]) -> None:
    order = [
        "pkgname",
        "pkgbase",
        "pkgver",
        "pkgdesc",
        "url",
        "builddate",
        "packager",
        "size",
        "arch",
        "license",
        "backup",
        "depend",
        "optdepend",
        "provides",
        "conflict",
        "replaces",
        "install",
    ]
    lines = [
        "# Generated by anonsurf's Arch packaging helper",
        "xdata = pkgtype=pkg",
    ]
    for key in order:
        value = meta.get(key)
        if value is None:
            continue
        values = value if isinstance(value, list) else [value]
        for item in values:
            lines.append(f"{key} = {item}")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def write_buildinfo(path: str, meta: dict[str, list[str] | str]) -> None:
    lines = [
        "format = 2",
        f"pkgname = {meta['pkgname']}",
        f"pkgbase = {meta['pkgbase']}",
        f"pkgver = {meta['pkgver']}",
        f"pkgarch = {meta['arch']}",
        f"packager = {meta['packager']}",
        f"builddate = {meta['builddate']}",
        f"builddir = {meta['pkgbase']}-{meta['pkgver']}",
    ]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def write_mtree(root: str, entries: list[str]) -> None:
    args = [
        "bsdtar",
        "-czf",
        os.path.join(root, ".MTREE"),
        "--format=mtree",
        "--options=!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link",
    ] + entries
    subprocess.run(args, cwd=root, check=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, help="directory with installed files")
    parser.add_argument("--out", required=True, help="output .pkg.tar.zst path")
    parser.add_argument("--pkgname", default="anonsurf")
    parser.add_argument("--pkgver", default="6.0.1-1")
    parser.add_argument("--pkgdesc", default="Anonymization toolkit for Tor routing")
    parser.add_argument("--url", default="https://www.parrotsec.org/")
    parser.add_argument("--arch", default="x86_64")
    parser.add_argument("--license", action="append", default=[])
    parser.add_argument("--depend", action="append", default=[])
    parser.add_argument("--optdepend", action="append", default=[])
    parser.add_argument("--backup", action="append", default=[])
    parser.add_argument("--conflict", action="append", default=[])
    parser.add_argument("--replace", action="append", default=[])
    parser.add_argument("--install-script")
    args = parser.parse_args()

    payload = sorted(
        name
        for name in os.listdir(args.root)
        if name not in {".PKGINFO", ".BUILDINFO", ".MTREE", ".INSTALL"}
    )

    meta: dict[str, list[str] | str] = {
        "pkgname": args.pkgname,
        "pkgbase": args.pkgname,
        "pkgver": args.pkgver,
        "pkgdesc": args.pkgdesc,
        "url": args.url,
        "builddate": str(int(time.time())),
        "packager": "AnonSurf CachyOS port",
        "size": str(installed_size(args.root)),
        "arch": args.arch,
        "license": args.license,
        "depend": args.depend,
        "optdepend": args.optdepend,
        "backup": args.backup,
        "conflict": args.conflict,
        "replaces": args.replace,
    }

    work = tempfile.mkdtemp(prefix="anonsurf-pkg-")
    try:
        for name in payload:
            src = os.path.join(args.root, name)
            dst = os.path.join(work, name)
            if os.path.isdir(src) and not os.path.islink(src):
                shutil.copytree(src, dst, symlinks=True)
            else:
                shutil.copy2(src, dst, follow_symlinks=False)

        write_pkginfo(os.path.join(work, ".PKGINFO"), meta)
        write_buildinfo(os.path.join(work, ".BUILDINFO"), meta)

        entries = [".PKGINFO", ".BUILDINFO"]
        if args.install_script:
            shutil.copy2(args.install_script, os.path.join(work, ".INSTALL"))
            os.chmod(os.path.join(work, ".INSTALL"), 0o644)
            entries.append(".INSTALL")
        entries.extend(payload)

        write_mtree(work, entries)

        if os.path.exists(args.out):
            os.remove(args.out)
        subprocess.run(
            ["bsdtar", "--zstd", "-cf", os.path.abspath(args.out)]
            + sorted(os.listdir(work)),
            cwd=work,
            check=True,
        )
    finally:
        shutil.rmtree(work, ignore_errors=True)

    print(args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
